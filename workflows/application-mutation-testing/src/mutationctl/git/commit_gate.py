from __future__ import annotations

from uuid import uuid4

from mutationctl.git.branch_plan import plan_branch
from mutationctl.models import CommitGateResult, CommitPlan, GitStatus
from mutationctl.validation.gates import evaluate_validation_gates


def plan_commit(
    store,
    git_status: GitStatus,
    allow_commit: bool,
    allow_production_fixes: bool = False,
    repo_slug: str = "repository",
) -> tuple[CommitPlan, CommitGateResult]:
    summary = evaluate_validation_gates(store, allow_commit=allow_commit)
    run = store.get_latest_run()
    run_id = run.run_id if run else f"run-{uuid4().hex[:8]}"
    branch = plan_branch(git_status.branch, repo_slug, run_id, [])
    allowed = []
    excluded = []
    for item in git_status.changed_files:
        file_allowed = _allowed_file(item.path) or (allow_production_fixes and item.allowed)
        (allowed if file_allowed else excluded).append(item.path)
    validation_passed = summary.required_gates_passed
    blockers = list(summary.blocking_gate_ids)
    if excluded:
        blockers.extend(excluded)
    if not allow_commit:
        blockers.append("allow_commit=false")
    commit_allowed = allow_commit and validation_passed and not excluded and branch.safe_to_create
    message = _commit_message(store, run_id)
    plan = CommitPlan(
        f"commit-plan-{uuid4().hex[:10]}",
        git_status.branch,
        branch.proposed_branch,
        message,
        allowed,
        excluded,
        f"validation-{run_id}",
        commit_allowed,
        blockers,
        [*git_status.evidence, *summary.evidence, *branch.evidence],
    )
    gate = CommitGateResult(
        "PASS" if commit_allowed else "BLOCKED",
        allow_commit,
        validation_passed,
        not excluded,
        branch.safe_to_create,
        commit_allowed,
        blockers,
        plan.evidence,
    )
    store.record_git_status(git_status)
    store.record_branch_plan(branch)
    store.record_commit_plan(plan)
    store.record_commit_gate_result(gate)
    return plan, gate


def execute_commit(plan: CommitPlan, adapter, store):
    if not plan.commit_allowed:
        from mutationctl.models import CommitExecutionResult
        result = CommitExecutionResult("BLOCKED", False, None, plan.proposed_branch, plan.commit_message, plan.reasons)
    else:
        result = adapter.execute_commit(plan)
    store.record_commit_execution_result(result)
    return result


def _allowed_file(path: str) -> bool:
    value = path.replace("\\", "/")
    name = value.rsplit("/", 1)[-1]
    return (
        value.startswith(("tests/", "test/", ".mutation-workflow/", "workflows/application-mutation-testing/"))
        or "/tests/" in f"/{value}"
        or name.startswith("test_")
        or name.endswith(("_test.py", ".test.js", ".spec.js", ".test.ts", ".spec.ts"))
        or name == "TODO_mutation-testing.md"
    )


def _commit_message(store, run_id: str) -> str:
    targets = [item.source_file for item in store.list_targets() if item.selected]
    rechecks = store.list_mutation_recheck_results()
    baseline = store.get_recheck_baseline()
    focused = store.list_focused_test_results()
    lines = ["test(mutation): harden tests for surviving mutants", "", "Targets:"]
    lines.extend(f"- {item}" for item in targets or ["Not available"])
    lines.extend(["", "Mutation evidence:"])
    if baseline:
        lines.append(f"- Baseline: {baseline.get('killed')} killed / {baseline.get('survived')} survived / {baseline.get('score')}")
    if rechecks:
        item = rechecks[-1]
        lines.append(f"- Recheck: {item.killed_after} killed / {item.survived_after} survived / {item.score_after}")
        if item.score_delta is not None:
            lines.append(f"- Delta: {item.score_delta:+.1f}")
    lines.extend(["", "Validation:", f"- Focused tests: {focused[-1].status if focused else 'NOT_RUN'}", f"- Mutation recheck: {rechecks[-1].status if rechecks else 'NOT_RUN'}", f"- Ledger rendered: {'PASS' if store.ledger_path.exists() else 'NOT_RUN'}", "", f"Generated by mutationctl run {run_id}"])
    return "\n".join(lines)
